-- BM-MFG-PILOT-001: one-door, fail-closed Manufacturing pilot.
-- Qoblex remains production. This gate is intentionally unusable until one SKU,
-- retail destination, and machine are explicitly approved.

create table if not exists public.manufacturing_pilot_gate (
  pilot_identifier text primary key,
  enabled boolean not null default false,
  approved_bom_id bigint references public.product_boms(id),
  approved_finished_product_id bigint references public.products(id),
  origin_location_id bigint not null references public.locations(id),
  destination_location_id bigint references public.locations(id),
  machine_code text check (machine_code in ('NIGHTHAWK','TERMINATOR')),
  approved_user_ids bigint[] not null,
  configured_by_user_id bigint references public.app_users(id),
  configured_at timestamptz,
  check (cardinality(approved_user_ids)=2)
);

create table if not exists public.manufacturing_pilot_orders (
  id bigint generated by default as identity primary key,
  pilot_identifier text not null references public.manufacturing_pilot_gate(pilot_identifier),
  work_order_number text not null unique,
  bom_id bigint not null references public.product_boms(id),
  finished_product_id bigint not null references public.products(id),
  origin_location_id bigint not null references public.locations(id),
  destination_location_id bigint not null references public.locations(id),
  machine_code text not null check (machine_code in ('NIGHTHAWK','TERMINATOR')),
  quantity integer not null check (quantity=1),
  status text not null check (status in ('draft','released','in_production','awaiting_shopify','shopify_confirmed','transfer_created','in_transit','received','closed','cancelled')),
  frozen_bom jsonb not null,
  frozen_bom_hash text not null,
  shopify_completion_reference text,
  shopify_transfer_link_id uuid references public.shopify_transfer_links(id),
  created_by_user_id bigint not null references public.app_users(id),
  released_at timestamptz,
  production_started_at timestamptz,
  completed_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists manufacturing_pilot_one_active
  on public.manufacturing_pilot_orders ((1))
  where status not in ('closed','cancelled');

create table if not exists public.manufacturing_pilot_allocations (
  pilot_order_id bigint not null references public.manufacturing_pilot_orders(id) on delete cascade,
  component_product_id bigint not null references public.products(id),
  required_quantity numeric not null check (required_quantity>0),
  consumed_quantity numeric not null default 0 check (consumed_quantity>=0),
  primary key (pilot_order_id,component_product_id)
);

alter table public.manufacturing_pilot_gate enable row level security;
alter table public.manufacturing_pilot_orders enable row level security;
alter table public.manufacturing_pilot_allocations enable row level security;
